#!/usr/bin/env bash
# Deploy the numerical.run SPA to /opt/sites/numerical — a self-hosted,
# basicauth-gated preview (Netlify serves the public site).
set -euo pipefail

SRC="$(cd "$(dirname "$0")" && pwd)/host"
DEST=/opt/sites/numerical
RUNTIME_SRC=/opt/runmat-runtime
MONACO_SRC=/opt/zoetrope-playground/static/monaco
V="$(date +%Y%m%d%H%M%S)"

mkdir -p "$DEST/examples" "$DEST/runtime"

# Single-page app. Inject asset locations (self-hosted here) + version stamp.
sed -e "s|__V__|$V|g" \
    -e "s|__RUNTIME__|/numerical/runtime|g" \
    -e "s|__FIGRENDER__|/numerical/runtime/figrender.mjs|g" \
    -e "s|__MONACO__|/numerical/monaco|g" \
    "$SRC/index.html" > "$DEST/index.html"
cp "$SRC/app.js" "$SRC/kernel.js" "$SRC/nbmd.js" "$SRC/md.js" "$SRC/render.js" "$SRC/importers.js" "$DEST/"
cp "$SRC/style.css" "$SRC/favicon.svg" "$DEST/"
cp "$SRC/lib.m" "$DEST/lib.m"
cp "$SRC"/examples/*.nb.md "$DEST/examples/"
# demo gallery: manifest + thumbnails (generated by gen-gallery.py)
[ -d "$SRC/thumbs" ] && mkdir -p "$DEST/thumbs" && cp "$SRC"/thumbs/*.png "$DEST/thumbs/" 2>/dev/null || true

# Monaco editor (vendored; shared with the zoetrope playground). Only copy if
# missing or stale, since it's a few MB of many files.
if [ ! -d "$DEST/monaco/vs" ]; then
  echo "vendoring Monaco from $MONACO_SRC …"
  cp -r "$MONACO_SRC" "$DEST/monaco"
fi

# RunMat WASM runtime + figrender (figrender ships in the repo under host/)
cp "$RUNTIME_SRC/runmat_wasm_web.js" "$RUNTIME_SRC/runmat_wasm_web_bg.wasm" "$DEST/runtime/"
cp "$SRC/../host/figrender.mjs" "$DEST/runtime/figrender.mjs" 2>/dev/null \
  || cp "$RUNTIME_SRC/figrender.mjs" "$DEST/runtime/figrender.mjs"

echo "deployed numerical.run v$V -> $DEST"
ls -la "$DEST"
